const dia = 0;
switch (dia) {
  case 0:
    "Domingo";
    break;
  case 1:
    "Lunes";
    break;
  case 2:
    "Martes";
    break;
  case 3:
    "Miercoles";
    break;
  case 4:
    "Jueves";
    break;
  case 5:
    "Viernes";
    break;
  case 6:
    "Sábado";
    break;

  default:
    break;
}

